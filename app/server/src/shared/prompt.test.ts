import test from "node:test";
import assert from "node:assert/strict";
import { promptTitle } from "./prompt";

// The server's thread title before it used the shared prompt parser (listener/text.ts until Phase 4), kept here to
// check the titles don't move.
const PASTE = /<pasted_content\b[^>]*>([\s\S]*?)(<\/pasted_content>|$)/g;
function oldTitle(text: string, max = 80): string | undefined {
  const command = /<command-name>([^<]*)/.exec(text)?.[1]?.trim();
  const args = /<command-args>([^<]*)<\/command-args>/.exec(text)?.[1]?.trim();
  if (command) return `${command}${args ? " " + args : ""}`.slice(0, max);
  const typed = text.replace(PASTE, " ").trim();
  const plain = (typed || text.replace(PASTE, "$1"))
    .replace(/<bash-input>([\s\S]*?)(<\/bash-input>|$)/g, "$ $1")
    .replace(/<(bash-stdout|bash-stderr)>[\s\S]*?(<\/\1>|$)/g, "")
    .replace(/<(local-command-caveat|local-command-stdout|local-command-stderr|system-reminder|command-message|command-args)>[\s\S]*?(<\/\1>|$)/g, "")
    .replace(/<\/?[a-z_-]+(\s[^>]*)?>/g, "")
    .trim();
  return plain ? plain.slice(0, max) : undefined;
}

const SAME = [
  "Fix the login bug in auth.ts",
  "  Add a dark mode toggle to the settings page, and make sure it remembers the choice across reloads please  ",
  "Two lines:\nfirst do this\nthen that",
  "What does `npm run build` do?\n\n```ts\nconst a = 1;\n```",
  "Use a Map<string, number> here",
  "<command-message>compact</command-message>\n<command-name>/compact</command-name>\n<command-args>focus on tests</command-args>",
  "<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>",
  "help me draft a reply to this?\n<pasted_content id=\"1\">\nDear team,\nThe launch moves to Friday.\n</pasted_content>",
  "<pasted_content id=\"2\">\nOnly the pasted text, nothing typed\n</pasted_content>",
  "<bash-input>git status</bash-input>",
  "<system-reminder>\nThe date changed.\n</system-reminder>\nNow run the tests",
  "Now run the tests\n<system-reminder>\nThe date changed.\n</system-reminder>",
  "<local-command-caveat>Caveat: the messages below were generated by the user while running local commands.</local-command-caveat>",
  "<local-command-stdout>Compacted</local-command-stdout>",
  "<system-reminder>only a note</system-reminder>",
  "[Image #1]\nWhat is wrong in this screenshot?",
  "<cross-session-message from-name=\"x\">hi there</cross-session-message>",
  "<ide_opened_file>The user opened the file /a/b.ts in the IDE.</ide_opened_file>",
  "",
];

test("thread titles are the same as before for normal prompts", () => {
  for (const p of SAME) assert.equal(promptTitle(p), oldTitle(p), JSON.stringify(p));
  assert.equal(promptTitle("x".repeat(200), 2000), oldTitle("x".repeat(200), 2000));
});

// Where the shared parser reads a prompt better than the old regex chain did (reported in the Phase 4 handoff).
test("blocks the old chain kept as words are left out of the title now", () => {
  const artifact = "<artifact-view-context artifact=\"https://claude.ai/artifact/abc\">\nThe person is looking at: Q3 plan\n</artifact-view-context>\nMake the chart bigger";
  assert.equal(oldTitle(artifact), "The person is looking at: Q3 plan\n\nMake the chart bigger");
  assert.equal(promptTitle(artifact), "Make the chart bigger");
  const onlyArtifact = "<artifact-view-context artifact=\"x\">\nlooking at a page\n</artifact-view-context>";
  assert.equal(oldTitle(onlyArtifact), "looking at a page");
  assert.equal(promptTitle(onlyArtifact), "looking at a page"); // only a block: what it says, as before
  const ide = "<ide_opened_file>The user opened the file /a/b.ts in the IDE.</ide_opened_file>\nexplain this";
  assert.equal(oldTitle(ide), "The user opened the file /a/b.ts in the IDE.\nexplain this");
  assert.equal(promptTitle(ide), "explain this");
  const html = "Why does <div class=\"x\"> collapse?";
  assert.equal(oldTitle(html), "Why does  collapse?");
  assert.equal(promptTitle(html), html);
});
